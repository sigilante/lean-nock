#!/usr/bin/env python3
"""Differential test: lean-nock's compiled formulas against NockVM.

    NOCKCHAIN_ROOT=/path/to/nockchain python3 diff/run.py

1. Build and run `export-corpus`: every case with lean-nock's own verdict.
2. Render and build the NockVM oracle against NOCKCHAIN_ROOT.
3. Run every program through NockVM and compare:
     value == value      AGREE
     CRASH == CRASH      AGREE
     TIMEOUT vs BUDGET   AGREE (both non-terminating within their bounds)
     anything else       MISMATCH
4. Check internal consistency: each `while` re-encoded as a recursive
   definition must get the same verdict as the `while` itself (Class D).
5. Write diff/results/results.tsv (every case) and diff/results/RESULTS.md.

Exits nonzero on any mismatch or inconsistency.
"""
import collections
import datetime
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ORACLE = ROOT / "diff" / "nockvm-oracle"
RESULTS = ROOT / "diff" / "results"
BUDGET = int(os.environ.get("NOCK_OP_BUDGET", "20000000"))


def sh(cmd, **kw):
    return subprocess.run(cmd, check=True, text=True, capture_output=True, **kw).stdout


def git_head(path):
    return sh(["git", "-C", str(path), "rev-parse", "HEAD"]).strip()


def main():
    nockchain = pathlib.Path(os.environ.get("NOCKCHAIN_ROOT", ROOT.parent / "nockchain")).resolve()
    nockvm = nockchain / "crates/nockvm/rust/nockvm"
    ibig = nockchain / "crates/nockvm/rust/ibig"
    if not (nockvm.is_dir() and ibig.is_dir()):
        sys.exit(f"nockvm/ibig not found under {nockchain}; set NOCKCHAIN_ROOT")

    # 1. lean-nock side
    sh(["lake", "build", "export-corpus"], cwd=ROOT)
    corpus = sh([str(ROOT / ".lake/build/bin/export-corpus")], cwd=ROOT)
    cases = [l.split("\t") for l in corpus.splitlines() if l.strip()]

    # 2. NockVM oracle
    gen = ORACLE / "generated"
    gen.mkdir(exist_ok=True)
    tmpl = (ORACLE / "Cargo.toml.in").read_text()
    (gen / "Cargo.toml").write_text(tmpl.replace("@NOCKVM@", str(nockvm)).replace("@IBIG@", str(ibig)))
    subprocess.run(["cargo", "build", "--release", "--quiet", "--manifest-path", str(gen / "Cargo.toml")],
                   cwd=ORACLE, check=True)
    binary = gen / "target/release/nockvm-oracle"

    # 3. run and compare
    programs = "\n".join(c[2] for c in cases) + "\n"
    out = subprocess.run([str(binary)], input=programs, text=True, capture_output=True, check=True,
                         cwd=ORACLE, env={**os.environ, "NOCK_OP_BUDGET": str(BUDGET)}).stdout.splitlines()
    if len(out) != len(cases):
        sys.exit(f"oracle returned {len(out)} lines for {len(cases)} cases")

    def classify(lean, vm, group=None):
        if group == "known":
            if lean == "CRASH" and vm == "PANIC":
                return "KNOWN-OPEN"
            if classify(lean, vm) != "MISMATCH":
                return "KNOWN-REMEDIATED"
            return "MISMATCH"
        if lean == vm and lean != "TIMEOUT":
            return "AGREE"
        if lean == "TIMEOUT" and vm == "BUDGET":
            return "AGREE-NONTERM"
        return "MISMATCH"

    rows = []
    for (group, name, program, lean), vm in zip(cases, out):
        rows.append((group, name, lean, vm, classify(lean, vm, group), program))

    # 4. internal consistency: while-as-recursion vs while
    verdict = {(g, n): lean for g, n, lean, _, _, _ in rows}
    inconsistent = []
    for g, n, lean, _, _, _ in rows:
        if g == "rec" and "-as-rec#" in n:
            base = n.replace("-as-rec#", "#")
            if verdict.get(("classd", base)) != lean:
                inconsistent.append((n, lean, verdict.get(("classd", base))))

    # 5. write results
    RESULTS.mkdir(exist_ok=True)
    with open(RESULTS / "results.tsv", "w") as f:
        f.write("group\tname\tlean-nock\tnockvm\tclass\tprogram\n")
        for r in rows:
            f.write("\t".join(r) + "\n")

    by_group = collections.OrderedDict()
    for g, _, _, _, cls, _ in rows:
        by_group.setdefault(g, collections.Counter())[cls] += 1
    mismatches = [r for r in rows if r[4] == "MISMATCH"]
    vm_kinds = collections.Counter(r[3] if not r[3][:1].isdigit() and not r[3].startswith("[") else "value"
                                   for r in rows if r[0] != "known")

    lines = [
        "# Differential test: lean-nock against NockVM",
        "",
        f"Generated by `diff/run.py` on {datetime.date.today().isoformat()}.",
        "",
        f"- lean-nock: `{git_head(ROOT)}`" + (" (with uncommitted changes)" if sh(["git", "-C", str(ROOT), "status", "--porcelain", "--", "Nock", "diff/ExportCorpus.lean"]).strip() else ""),
        f"- nockchain: `{git_head(nockchain)}` (`crates/nockvm`, no jets warm)",
        f"- lean-nock fuel: 200000 steps per case (`nockF`); NockVM op budget: {BUDGET} work items per case",
        "",
        "Verdicts: a noun, `CRASH` (deterministic `%exit`), `TIMEOUT` (lean-nock: no verdict within fuel), "
        "`BUDGET` (NockVM: op budget exhausted). `TIMEOUT` against `BUDGET` counts as agreement: both are "
        "consistent with divergence, and neither proves it.",
        "",
        "| group | cases | agree | agree (non-terminating) | mismatch |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    tot = collections.Counter()
    for g, c in by_group.items():
        if g == "known":
            continue
        n = sum(c.values())
        tot.update(c)
        lines.append(f"| `{g}` | {n} | {c['AGREE']} | {c['AGREE-NONTERM']} | {c['MISMATCH']} |")
    lines.append(f"| **total** | {sum(tot.values())} | {tot['AGREE']} | {tot['AGREE-NONTERM']} | {tot['MISMATCH']} |")
    known = [r for r in rows if r[0] == "known"]
    if known:
        lines += ["", "## Known NockVM divergence (harness sensitivity)", "",
                  "Opcode-10 edits at an invalid axis, which Λ never emits. Nock specifies a deterministic "
                  "crash; `KNOWN-OPEN` means NockVM still panics, `KNOWN-REMEDIATED` that it now agrees.", "",
                  "| case | lean-nock | NockVM | status |", "| --- | --- | --- | --- |"]
        lines += [f"| `{n}` | `{l}` | `{v}` | {c} |" for _, n, l, v, c, _ in known]
    lines += ["", "NockVM verdict kinds: " + ", ".join(f"{k} {v}" for k, v in sorted(vm_kinds.items())) + ".", ""]
    lines += ["Internal consistency (each `while` re-encoded as a recursive definition gets the same verdict "
              f"as the `while`): {'OK' if not inconsistent else f'{len(inconsistent)} INCONSISTENT'}.", ""]
    if mismatches:
        lines += ["## Mismatches", "", "| group | name | lean-nock | NockVM |", "| --- | --- | --- | --- |"]
        lines += [f"| `{g}` | `{n}` | `{l}` | `{v}` |" for g, n, l, v, _, _ in mismatches]
        lines.append("")
    lines += ["Every case, with its program, is in `results.tsv`."]
    (RESULTS / "RESULTS.md").write_text("\n".join(lines) + "\n")

    print("\n".join(lines))
    if mismatches or inconsistent:
        for x in inconsistent:
            print("INCONSISTENT", x)
        sys.exit(1)


if __name__ == "__main__":
    main()
